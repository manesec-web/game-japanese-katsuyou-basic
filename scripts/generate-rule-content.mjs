// Generator for src/data/rule-content.js (學習 / 變形說明).
//
// It is deliberately thin: it reads the real verbs from vol/, hands them to the
// pure builder in src/study/rule-content-builder.js, and writes the result. The
// conjugation tables, the 段 / 音便 mappings, the special-case notes and the
// example rows all live in pure .js modules, never in a .vue file.
//
// Run: node scripts/generate-rule-content.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { buildRuleContent, checkExampleForms, collectExamples, EXAMPLE_GODAN } from '../src/study/rule-content-builder.js'
import { FORM_IDS } from '../src/dict/forms.js'

const LESSONS = Array.from({ length: 50 }, (_, i) => i + 1)

function loadVerbs() {
  const verbs = []
  for (const lesson of LESSONS) {
    const file = new URL(`../vol/lesson_${lesson}.json`, import.meta.url)
    const data = JSON.parse(readFileSync(file, 'utf8'))
    for (const verb of data[`lesson_${lesson}`]?.vols ?? []) verbs.push({ lesson, verb })
  }
  return verbs
}

const verbs = loadVerbs()
const examples = collectExamples(verbs)

// Every example's written form must be exactly kanjiPrefix + kana ending; this
// catches an okurigana / reading mismatch before it is published 210 times.
for (const { verb } of Object.values(examples)) {
  const errors = checkExampleForms(verb)
  if (errors.length) {
    throw new Error(`inconsistent example ${verb['dictionary-form'].vol}: ${JSON.stringify(errors)}`)
  }
}

// Each 五段 ending must have exactly one example, so the 音便 table can be shown
// in the standard teaching order (う・つ・る / む・ぶ・ぬ / く・ぐ / す).
const endings = new Set(EXAMPLE_GODAN.map((key) => Array.from(examples[key].verb['dictionary-form'].japanese).slice(-1)[0]))
for (const ending of ['う', 'く', 'ぐ', 'す', 'つ', 'ぬ', 'ぶ', 'む', 'る']) {
  if (!endings.has(ending)) throw new Error(`no 五段 example for the ${ending} ending`)
}

const content = buildRuleContent(examples)
if (content.length !== FORM_IDS.length * (FORM_IDS.length - 1)) {
  throw new Error(`expected 210 entries, got ${content.length}`)
}

const header = `// Authored explanations for the 學習 (grammar reference) mode.\n` +
  `//\n` +
  `// Generated by scripts/generate-rule-content.mjs — do not edit by hand.\n` +
  `// One entry per ordered pair with 從 ≠ 到 (15 × 14 = 210 entries). The shape\n` +
  `// is described in docs/spec.md → 學習 → 學習內容. The tables, the 段 / 音便\n` +
  `// mappings and the special-case notes come from the pure rules in\n` +
  `// src/study/rule-conjugation.js and src/study/rule-content-builder.js.\n` +
  `//\n` +
  `// Each entry is { from, to, sections: [{ heading, rule, map?, columns, rows,\n` +
  `// notes }] }. A row is { from, change?, to } of { t, c } segments, where c is\n` +
  `// 'change' (purple) or 'removed' (red double strikethrough). map is the\n` +
  `// optional { label, rows: [{ line, note }] } kana mapping. notes are the\n` +
  `// { t, c } special-case annotations printed after the table.\n\n`

const out = header + `export const RULE_CONTENT = ${JSON.stringify(content, null, 2)}\n`
writeFileSync(new URL('../src/data/rule-content.js', import.meta.url), out, 'utf8')
console.log(`wrote ${content.length} entries to src/data/rule-content.js`)
